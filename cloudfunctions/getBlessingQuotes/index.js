async function seedQuotes(startIndex = 0) {
  const batch = 20
  const emojis = ['💒', '☺️', '😄', '🌹', '💕', '✨', '🎊', '🌸', '💫', '🌈', '💖', '🥂', '🍾', '💐', '🎉', '❤️', '🤍', '🧡']
  for (let i = startIndex; i < QUOTES.length; i += batch) {
    const chunk = QUOTES.slice(i, Math.min(i + batch, QUOTES.length)).map((text, idx) => {
      const emoji = emojis[(i + idx) % emojis.length]
      return { text: text + ' ' + emoji, createdAt: db.serverDate() }
    })
    await db.collection('blessingQuotes').add({ data: chunk })
  }
}

exports.main = async (event, context) => {
  try {
    let total = 0
    try {
      const res = await db.collection('blessingQuotes').count()
      total = res.total || 0
    } catch (countErr) {
      // 集合不存在时自动创建（匹配多种错误表述）
      const msg = (countErr.message || countErr.errMsg || '').toLowerCase()
      if (
        msg.includes('not found') ||
        msg.includes('not exists') ||
        msg.includes('not exist') ||
        msg.includes('不存在') ||
        msg.includes('invalid collection') ||
        msg.includes('collection not')
      ) {
        console.log('集合不存在，尝试创建...')
        await db.createCollection('blessingQuotes')
        console.log('集合创建成功')
      } else {
        throw countErr
      }
    }

    // 库为空或不足时自动 seed（支持增量补充）
    if (total < QUOTES.length) {
      console.log(`当前 ${total} 条，目标 ${QUOTES.length} 条，补充差额...`)
      await seedQuotes(total)
      const res = await db.collection('blessingQuotes').count()
      total = res.total || 0
      console.log(`补充完成，当前共 ${total} 条`)
    }

    const listRes = await db.collection('blessingQuotes').get()
    return { success: true, data: listRes.data || [], total: listRes.data.length }
  } catch (err) {
    console.error('getBlessingQuotes error:', err)
    return { success: false, data: [], message: err.message || '查询失败' }
  }
}
